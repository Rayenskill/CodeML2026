"""Strategy 21 (needs an external API key, NOT run for the submitted results): real-looking handwriting from an
image model (Gemini) to widen the recogniser's training distribution beyond fonts.

Only *fictitious* values are sent (sampled from the field grammars of strategy 5) and only generated images come
back: no photo, no crop, no patient data ever leaves the machine. The privacy guard below enforces it in code.

Pipeline (one API call = one sheet of 12 handwritten lines, ~10 kept after checks):
  sample N values -> prompt -> image model -> segment N lines -> keep a line only if the recogniser can read the
  expected text in it (CTC likelihood) -> ink patch (RGBA) -> bank (hw_bank/bank.jsonl + PNGs)
synth_pages.synth_page(..., bank=load_bank(...), bank_p=0.3) then pastes bank patches into the form cells, so the
crops still go through the real degradation + registration pipeline with exact labels.

--dry_run replaces the API call by a font-rendered sheet: every other step (guard, segmentation, verification,
bank, synthesis) runs offline and is covered by test_gemini_handwriting.py.

pip install google-genai ; set GEMINI_API_KEY=...
python gemini_handwriting.py --sheets 300 --out ~/dayone_local/hw_bank [--dry_run] [--model gemini-2.5-flash-image]
"""
